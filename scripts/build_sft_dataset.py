with open(DATA / 'eval_questions.jsonl', encoding='utf-8') as f:
    eval_questions = [json.loads(line) for line in f if line.strip()]
EVAL_NORM = [' '.join(re.findall(r'\w+', r['question'].lower(), flags=re.UNICODE)) for r in eval_questions]


def normalize(s):
    return ' '.join(re.findall(r'\w+', s.lower(), flags=re.UNICODE))


def overlap_risk(question: str) -> tuple[float, str]:
    q = normalize(question)
    candidates = [(SequenceMatcher(None, q, e).ratio(), r['id']) for e, r in zip(EVAL_NORM, eval_questions)]
    return max(candidates, default=(0, ''))


def vary_index(s: str) -> int:
    return int(hashlib.blake2b(s.encode(), digest_size=4).hexdigest(), 16)


def make_plant(parts):
    name, gen, dat, latin, group, light, water, humidity, root, special, sid = parts
    return dict(name=name,gen=gen,dat=dat, latin=latin,group=group,light=light,water=water,
                humidity=humidity,root=root,special=special,source=sid,acc=ACC[name],ins=INS[name])


def make_care(p, case):
    qfmt = CARE_ALT_QUESTIONS[case] if vary_index(p['latin'] + case) % 2 else CARE_QUESTIONS[case]
    q = qfmt.format(**p)
    conditions, actions = CARE_ADVICE[case]
    c, a = conditions(p), actions(p)
    suffix = 'Если состояние растения меняется, корректируйте один фактор за раз и наблюдайте за новыми листьями.'
    if vary_index(p['latin'] + case) % 3 == 0:
        a[-1] += ' ' + suffix
    a_out = '\n'.join(f'{j}. {s}' for j,s in enumerate(a, 1))
    c_out = '\n'.join('- '+s for s in c)
    return q, f'Условия:\n{c_out}\n\nРекомендации:\n{a_out}'


def make_diag(p, case):
    qfmt = DIAG_ALT_QUESTIONS[case] if vary_index(case + p['latin']) % 2 else DIAG_QUESTIONS[case]
    q = qfmt.format(**p)
    fields = DIAG_DATA[case]
    why = fields['why'][:]
    checks = fields['checks'][:]
    do = fields['do'][:]
    if p['group'] in ['succulent','semi'] and case in ['yellowing','wilt','curl','gnats']:
        checks.append('Для этого вида отдельно учитывайте запас воды в листьях: не поливайте только по календарю.')
    elif p['group'] == 'orchid' and case in ['yellowing','wilt','brown_spots','soft_base']:
        checks.append('У фаленопсиса отдельно оцените состояние корней и просыхание коры, а не обычной почвы.')
    elif p['group'] == 'humid' and case in ['crispy_tips','curl','yellowing']:
        checks.append('Для влаголюбивого вида сравните влажность воздуха и грунта: это разные показатели.')
    elif p['group'] == 'ficus' and case in ['leaf_fall','yellowing','pale_growth']:
        checks.append('У фикуса проверьте также недавнюю перестановку и холодные сквозняки.')
    if case in ['yellowing','curl','wilt','pale_growth','crispy_tips']:
        do.append(f'Ориентир для обычного ухода за этим видом: {p["water"]}.')
    if case == 'sunburn':
        do.append(f'Уточнение по освещению вида: {p["light"]}.')
    why_out = '\n'.join('- ' + x for x in why)
    checks_out = '\n'.join(f'{i}. {x}' for i, x in enumerate(checks,1))
    do_out = '\n'.join(f'{i}. {x}' for i, x in enumerate(do,1))
    return q, f'Возможные причины:\n{why_out}\n\nЧто проверить:\n{checks_out}\n\nЧто делать:\n{do_out}'


# pick species-specific cases across the pool while withholding the topic types of evaluation scenarios.
all_records = []
for pi, parts in enumerate(PLANTS):
    p = make_plant(parts)
    care_ex, diag_ex = EVAL_EXCLUDE.get(p['name'], (set(), set()))
    care_eligible = [c for c in CARE_CASES if c not in care_ex]
    diag_eligible = [d for d in DIAG_CASES if d not in diag_ex]
    care_order = care_eligible[pi % len(care_eligible):] + care_eligible[:pi % len(care_eligible)]
    diag_order = diag_eligible[(pi * 3) % len(diag_eligible):] + diag_eligible[:(pi * 3) % len(diag_eligible)]
    care_selected = care_order[:8]
    diag_selected = diag_order[:8]
    for task, cases in [('care',care_selected), ('diagnosis',diag_selected)]:
        for ci, case in enumerate(cases):
            q, a = make_care(p, case) if task == 'care' else make_diag(p, case)
            extra = [p['source'], 'S01','S03'] if task == 'care' else [p['source'], DIAG_DATA[case]['src'],'S04']
            extra = list(dict.fromkeys(extra))
            rec = {
               'id':f'SFT-{len(all_records)+1:04d}',
               'plant':p['name'],'latin':p['latin'],'task':task,'scenario':case,
               'question':q,'answer':a,'source_ids':extra,
               'source_urls':[SOURCE[sid][1] for sid in extra],
               'generation_method':'curated_structured_synthesis',
               'quality_note':'automated_consistency_checks_only',
            }
            all_records.append(rec)

